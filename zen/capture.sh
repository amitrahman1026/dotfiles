#!/bin/bash
# Copy Zen settings that the Mozilla account does not sync from the live
# profile back into this folder. Run it after you change the layout or
# shortcuts in Zen, then commit.
set -euo pipefail
dir=$(cd "$(dirname "$0")" && pwd)
. "$dir/profiles.sh"

profile=$(zen_profiles | head -n 1)
[ -n "$profile" ] || { echo "no Zen profile found" >&2; exit 1; }

{
  echo '// Zen settings not synced by the Mozilla account. Generated by capture.sh.'
  grep -F -e 'user_pref("zen.view.use-single-toolbar"' \
          -e 'user_pref("zen.view.compact.enable-at-startup"' \
          -e 'user_pref("zen.tabs.show-newtab-vertical"' \
          -e 'user_pref("xpinstall.signatures.required"' \
          -e 'user_pref("browser.uiCustomization.state"' \
          "$profile/prefs.js"
} > "$dir/user.js"
cp "$profile/zen-keyboard-shortcuts.json" "$dir/"
echo "captured from $profile"
